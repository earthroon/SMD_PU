import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { HOME_R4B_HELMET, HOME_R4B_CARD3_TITLE, resolveR4BHelmetCandidate } from '../../app/data/figma-r2-visual-r4b.ts';

const root=resolve(import.meta.dirname,'../..');
const bytes=rel=>readFileSync(join(root,rel));
const text=rel=>bytes(rel).toString('utf8');
const hash=b=>createHash('sha256').update(b).digest('hex');
const skin=text('docs/migration/smd-home-r2/cf1/figma-source/skin.jsonl').trim().split(/\r?\n/).filter(Boolean).map(JSON.parse);
const nodes=new Map(skin.filter(x=>x.kind==='node').map(x=>[x.nodeKey,x]));
assert.equal(nodes.size,272,'Frozen Figma node count');
const helmet=HOME_R4B_HELMET;
assert.equal(helmet.nodeKey,'node-1:482');
assert.equal(helmet.parentNodeKey,'node-1:95');
assert.equal(helmet.sourceWidth,104);
assert.equal(helmet.sourceHeight,64);
assert.deepEqual(nodes.get(helmet.nodeKey)?.rectLocal,[116,54,104,64]);
assert.equal(nodes.get(helmet.nodeKey)?.parent,'node-1:95');
assert.equal(nodes.get(helmet.nodeKey)?.nodeKind,'VECTOR');
assert.equal(helmet.sourceAssetId,'asset-'+helmet.sourceAssetSha256);
const origSvg=`public/figma-r2/assets/${helmet.sourceAssetId}.svg`;
assert.equal(hash(bytes(origSvg)),helmet.sourceAssetSha256);
assert.equal(hash(bytes(`docs/migration/smd-home-r2/cf1/figma-source/assets/${helmet.sourceAssetId}.svg`)),helmet.sourceAssetSha256);
assert.deepEqual(resolveR4BHelmetCandidate(helmet.nodeKey,helmet.sourceAssetId,helmet.sourceAssetSha256),helmet);
assert.equal(resolveR4BHelmetCandidate('node-1:477',helmet.sourceAssetId,helmet.sourceAssetSha256),null);
assert.throws(()=>resolveR4BHelmetCandidate(helmet.nodeKey,'asset-incorrect',helmet.sourceAssetSha256),/IDENTITY_MISMATCH/);
assert.throws(()=>resolveR4BHelmetCandidate(helmet.nodeKey,helmet.sourceAssetId,'other'),/IDENTITY_MISMATCH/);

const svgVue=text('app/components/figma/FigmaSvgAsset.vue');
assert.match(svgVue,/import \{resolveR4BHelmetCandidate\} from '~\/data\/figma-r2-visual-r4b';/);
assert.match(svgVue,/r4bHelmet=computed\(\(\)=>resolveR4BHelmetCandidate\(props\.nodeKey,props\.assetId,asset\.value\?\.sha256\)\)/);
const branch=svgVue.match(/<image\s+v-else-if="asset && visual\?\.kind==='helmet-weight' && r4bHelmet"[\s\S]*?\/>/g)??[];
assert.equal(branch.length,1,'Exactly one selected helmet branch');
assert.match(branch[0],/:href="asset\.src"/);
assert.match(branch[0],/preserveAspectRatio="xMidYMid meet"/);
assert.match(branch[0],/:width="inkWidth" :height="inkHeight"/);
assert.match(branch[0],/:data-original-svg-sha256="asset\.sha256"/);
assert.match(branch[0],/:data-r4b-candidate="r4bHelmet\.renderedCandidateId"/);
assert.doesNotMatch(branch[0],/visual\.href|derived-svg-sha256|feMorphology/);
assert.equal(helmet.renderedCandidateId,'B1_CANONICAL_SOURCE_NO_EROSION');
assert.equal(helmet.qualification,'VISUAL_PENDING');
const baseline=text('public/figma-r2/derived/helmet-weight-r3.svg');
assert.match(baseline,/operator="erode" radius="0\.65"/);
// Existing source manifest remains a baseline only; no changes to R3 source or original asset bytes.
assert.equal(readdirSync(join(root,'public/figma-r2/assets')).filter(f=>f.endsWith('.svg')).length,31);
console.log('PASS_R4B_CF14_SOURCE_HELMET_B1_SELECTED');

