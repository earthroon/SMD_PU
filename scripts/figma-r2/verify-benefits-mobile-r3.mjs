import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
const root=resolve(import.meta.dirname,'../..');
const read=file=>readFileSync(join(root,file),'utf8');
const css=read('app/assets/css/home-r2.css');
const start='/* SMD-HOME-R2-MOBILE-BENEFITS-R1 BEGIN: Vue3 Semantic Reflow only */';
const end='/* SMD-HOME-R2-MOBILE-BENEFITS-R1 END */';
assert.equal(css.split(start).length,2,'benefits R1 marker unique');
assert.equal(css.split(end).length,2,'benefits R1 marker end unique');
const region=css.slice(css.indexOf(start),css.indexOf(end)+end.length).replace(/\r\n/g,'\n').trimEnd();
const hash=createHash('sha256').update(region).digest('hex');
const expected='95867caff224484ff2457cd3b8ca971b50246f4de68e4f1817871d7e0fbf5f02';
assert.equal(hash,expected,'R3 exact CSS fragment SHA');
assert.match(region,/R3-LINEBOX supersession/);
const parent=region.match(/\.smd-home--benefits \.smd-home__benefit-description\s*\{([^}]+)\}/)?.[1];
assert.ok(parent,'description parent selector');
assert.match(parent,/font-size:\s*clamp\(11px, 3vw, 12px\);/);
assert.match(parent,/line-height:\s*1\.5;/);
const child=region.match(/\.smd-home--benefits \.smd-home__benefit-description \.smd-home-figma-text,\s*\.smd-home--benefits \.smd-home__benefit-description \.smd-home-figma-text > span\s*\{([^}]+)\}/)?.[1];
assert.ok(child,'description wrapper + run selectors');
assert.match(child,/font-size:\s*inherit !important;/);
assert.match(child,/line-height:\s*inherit !important;/);
assert.ok(!child.includes('font-size: clamp'),'no child competing font-size authority');
const vue=read('app/components/home/HomeBenefits.vue');
for(const key of ['card.numeral','card.title','card.description']) assert.ok(vue.includes(`:text-key="${key}"`),key);
assert.equal((vue.match(/<HomeMediaFrame\s+:slot-id="card.slot"\s*\/>/g)||[]).length,1);
assert.ok(vue.includes('smd-home__benefit-card'));
assert.ok(read('app/components/home/HomeMediaFrame.vue').includes('resolveHomeR2PublicImage('));
assert.match(region,/grid-template-columns:\s*repeat\(2, minmax\(0, 1fr\)\)/);
assert.match(region,/margin-top:\s*8px;/);
assert.match(region,/margin:\s*0 0 6px;/);
assert.ok(!region.includes('min-height: clamp(248px'));
