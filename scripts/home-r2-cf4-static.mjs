import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { homeHeaderNavigationV2,assertHomeHeaderNavigationV2 } from '../app/data/home-r2-navigation.ts';
import { resolveHomeScaffoldPath } from '../app/utils/homeR2ScaffoldAdmission.ts';
import { verifyUntouchedFiles } from './lib/home-r2-source.mjs';
import { TEXT_HEADER_AUTHORIZED_DIGESTS } from './lib/home-r2-text-header-authority.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=n=>readFileSync(resolve(root,n),'utf8');
assertHomeHeaderNavigationV2();
assert.deepEqual(homeHeaderNavigationV2.items.map(x=>x.to),['/about','/curriculum','/archive','/reviews','/faq']);
assert.deepEqual(homeHeaderNavigationV2.items.map(x=>x.label),['아카데미소개','교육과정','수강갤러리','수강후기','Q&A']);
assert.equal(homeHeaderNavigationV2.cta.label,'상담신청');
for(const p of ['/reviews','/faq'])assert.equal(resolveHomeScaffoldPath(p),p);
for(const p of ['','/','/about','/admin','/admin/foo','/reviews/','/faq/','/reviews-old','/unknown','/FAQ'])assert.equal(resolveHomeScaffoldPath(p),null);
const header=read('app/components/feature/SiteHeader.vue');
assert.match(header,/homeHeaderNavigationV2\.items/);
assert.match(header,/:to="item\.to"/);
assert.match(header,/aria-controls="smd-header-menu-drawer"/);
assert.match(header,/:aria-expanded="open"/);
assert.match(header,/event\.key === 'Escape'/);
assert.match(header,/releaseDrawerLock\(\)/);
assert.match(header,/target="_blank" rel="noopener noreferrer"/);
assert.doesNotMatch(header,/router\.push|preventDefault\(/);
const app=read('app/app.vue');
assert.match(app,/admitHomeScaffold\(path, payload\)/);
assert.match(app,/resolveHomeScaffoldPath\(path\)/);
assert.match(app,/sourcePath = scaffold === null \? path : '\/'/);
assert.match(app,/selected\.value = null; \/\/ A scaffold is not a CMS category/);
assert.match(app,/scaffoldAdmissionCurrent\(r, route\.path\)/);
assert.match(app,/SMD_HOME_R2_SCAFFOLD_SOURCE_IDENTITY_DRIFT/);
assert.doesNotMatch(read('server/api/render.get.ts'),/\/reviews|\/faq/);
for(const [slug,title] of [['reviews','수강후기'],['faq','Q&A']]){
 const page=read(`app/pages/${slug}.vue`);
 assert.match(page,/noindex,follow/);
 assert.ok(page.includes(`data-scaffold-route="/${slug}"`));
 assert.ok(page.includes(title==='Q&A'?'Q&amp;A':title));
 assert.doesNotMatch(page,/<SiteHeader|<SiteFooter|<CmsSlot/);
}
assert.ok(verifyUntouchedFiles(root,TEXT_HEADER_AUTHORIZED_DIGESTS)>=21);
console.log('PASS_SMD_HOME_R2_CF4_NAVIGATION_SCAFFOLD_STATIC');
